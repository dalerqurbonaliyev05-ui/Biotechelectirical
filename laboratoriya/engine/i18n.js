let joriy = 'uz';
const kuzatuvchilar = new Set();

export const til = () => joriy;

export function t(key, p) {
  let s = (L[joriy] && L[joriy][key]) ?? L.uz[key] ?? key;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : m));
  return s;
}

/** {uz, ru, en} obyektidan joriy tildagi matnni oladi. */
export function tx(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[joriy] ?? obj.uz ?? '';
}

export function tilniOrnat(lang) {
  if (!L[lang]) lang = 'uz';
  joriy = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { const v = t(el.dataset.i18nTitle); el.setAttribute('title', v); el.setAttribute('aria-label', v); });
  document.querySelectorAll('.lang-btn').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* xotira yopiq bo‘lishi mumkin */ }
  kuzatuvchilar.forEach((f) => f(lang));
}

export function tilniKuzat(f) { kuzatuvchilar.add(f); }

export function i18nBoshlash() {
  document.querySelectorAll('.lang-btn').forEach((b) => b.addEventListener('click', () => tilniOrnat(b.dataset.lang)));
  let saqlangan = null;
  try { saqlangan = localStorage.getItem(LANG_KEY); } catch (e) { /* e’tiborsiz */ }
  tilniOrnat(saqlangan && L[saqlangan] ? saqlangan : 'uz');
}
